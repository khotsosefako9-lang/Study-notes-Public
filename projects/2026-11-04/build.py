#!/usr/bin/env python3
"""Build the 4 Nov Who Said It? cut list and props from plan.json.

  python3 projects/2026-11-04/build.py <chunk transcripts dir>

Run roughcut.py on the cut list, then run this again so timings use the
measured segment starts in public/footage/who-said-it-2026-11-04.segments.json.
"""
import glob
import json
import math
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..")
NAME = "who-said-it-2026-11-04"

# From the Bible study games site (Who Said It? segment), in its option order.
QUESTIONS = [
    ("Am I my brother's keeper?", ["Cain", "Abel", "Adam", "Esau"], 0, "Genesis 4:9"),
    ("Here am I. Send me!", ["Isaiah", "Jeremiah", "Moses", "Samuel"], 0, "Isaiah 6:8"),
    ("Where you go I will go, and where you stay I will stay.", ["Ruth", "Naomi", "Esther", "Orpah"], 0, "Ruth 1:16"),
    ("Surely this man was the Son of God!", ["A Roman centurion", "Peter", "Pontius Pilate", "Thomas"], 0, "Mark 15:39"),
    None, None,
    ("And who knows but that you have come to your royal position for such a time as this?", ["Mordecai", "Esther", "King Xerxes", "Haman"], 0, "Esther 4:14"),
    None, None,
    ("You are the Messiah, the Son of the living God.", ["Peter", "John", "Andrew", "James"], 0, "Matthew 16:16"),
    None,
    None,
    ("Lord, do not hold this sin against them.", ["Stephen", "Paul", "Peter", "James"], 0, "Acts 7:60"),
    ("I am the Lord's servant. May your word to me be fulfilled.", ["Mary, mother of Jesus", "Elizabeth", "Hannah", "Anna"], 0, "Luke 1:38"),
    ("Meaningless! Meaningless! Everything is meaningless.", ["The Teacher", "Job", "Jonah", "Jeremiah"], 0, "Ecclesiastes 1:2"),
]
BANNED = re.compile(r"fuck|shit|damn", re.I)


def load_words(tdir, clip):
    words = []
    for f in sorted(glob.glob(os.path.join(tdir, f"{clip}_*.json"))):
        off = 60.0 * int(re.search(r"_(\d+)\.json$", f).group(1))
        for s in json.load(open(f))["segments"]:
            for w in s.get("words", []):
                words.append({"text": w["word"].strip(), "start": w["start"] + off, "end": w["end"] + off})
    return words


def main():
    tdir = sys.argv[1]
    plan = json.load(open(os.path.join(HERE, "plan.json")))
    zoom = " ".join(str(z) for z in plan["zoom"])

    segs = []  # (round index, clip, a, b)
    for ri, r in enumerate(plan["rounds"]):
        for a, b in r["segments"]:
            segs.append((ri, r["clip"], a, b))
    with open(os.path.join(HERE, "cuts.txt"), "w") as f:
        f.write("# Who Said It?, 4 Nov 2026. Generated by build.py from plan.json.\n")
        for _, clip, a, b in segs:
            f.write(f"raw/2026-11-04/VID_20261104_{clip}.mp4 {a} {b} {zoom}\n")

    measured = os.path.join(ROOT, "public", "footage", f"{NAME}.segments.json")
    if os.path.exists(measured) and len(json.load(open(measured))["starts"]) == len(segs):
        m = json.load(open(measured))
        starts, end = m["starts"], round(sum(m["lengths"]), 2)
    else:
        starts, t = [], 0.0
        for _, _, a, b in segs:
            starts.append(round(t, 3)); t += (math.ceil(round((b - a) * 30, 3)) + 1) / 30
        end = round(t, 2)

    def out(ri, src):
        """Map a source time in round ri onto the edited timeline (nearest kept segment)."""
        best = None
        for k, (r, _, a, b) in enumerate(segs):
            if r != ri:
                continue
            if a <= src <= b:
                return round(starts[k] + src - a, 2)
            d = a - src if src < a else src - b
            edge = starts[k] if src < a else starts[k] + b - a
            if best is None or d < best[0]:
                best = (d, round(edge, 2))
        return best[1]

    matchups, stamps, rules = [], [], None
    cain = plan["matchup5CainBy"]  # 0 = lady said Cain, 1 = gent said Cain
    for ri, r in enumerate(plan["rounds"]):
        if r.get("hook"):
            continue
        q, options, answer, ref = QUESTIONS[r["q"]]
        picks = r["picks"]
        if picks == "matchup5":
            picks = [] if cain is None else [[cain, 0, 16.4], [1 - cain, 1, 20.6]]
        m = {"at": out(ri, r["segments"][0][0]), "players": r["players"], "quote": q, "options": options, "answer": answer, "ref": ref,
             "quoteAt": out(ri, r["quoteAt"]), "optionsAt": out(ri, r["optionsAt"]),
             "picks": [{"team": team, "option": opt, "at": out(ri, at)} for team, opt, at in picks],
             "revealAt": out(ri, r["revealAt"])}
        if r.get("noScore"):
            m["noScore"] = True
        if r.get("label"):
            m["label"] = r["label"]
        matchups.append(m)
        if "rules" in r:
            rules = {"at": out(ri, r["rules"][0]) + 0.1, "until": out(ri, r["segments"][1][0]) + 2.2}
        if not r.get("noScore"):
            right = [p[0] for p in picks if p[1] == answer]
            if right:
                who = "Ladies" if right == [0] else "Gents" if right == [1] else "Both"
                stamps.append({"at": out(ri, r["revealAt"]) + 0.3, "text": f"{who} score!" if who != "Both" else "Both right!",
                               "tone": "gold" if who == "Ladies" else "green", "duration": 1.2})

    # Final result (only when matchup 5 is known)
    total = [0, 0]
    for r in plan["rounds"]:
        if r.get("hook") or r.get("noScore"):
            continue
        picks = r["picks"]
        if picks == "matchup5":
            if cain is None:
                total = None
                break
            picks = [[cain, 0, 0]]
        q = QUESTIONS[r["q"]]
        for team, opt, _ in picks:
            if opt == q[2]:
                total[team] += 1
    final_at = round(max(matchups[-1]["revealAt"] + 0.9, end - 3.6), 2)
    if total:
        text = "It's a draw!" if total[0] == total[1] else ("Ladies win!" if total[0] > total[1] else "Gents win!")
        stamps.append({"at": final_at, "text": f"{text} {max(total)}–{min(total)}", "tone": "gold", "duration": round(end - final_at, 2)})

    words = {c: load_words(tdir, c) for c in {s[1] for s in segs}}
    caps = []
    for k, (ri, clip, a, b) in enumerate(segs):
        fixes = plan["fixes"].get(clip, {})
        for w in words[clip]:
            if a <= w["start"] < b - 0.05 and fixes.get(w["text"], w["text"]):
                caps.append({"text": fixes.get(w["text"], w["text"]), "start": round(starts[k] + w["start"] - a, 2),
                             "end": round(starts[k] + min(w["end"], b) - a, 2)})
    bad = [c["text"] for c in caps if BANNED.search(c["text"])]
    if bad:
        sys.exit(f"Caption words need fixing: {bad}")

    props = {
        "title": "Who Said It? The Decider", "teams": ["Ladies", "Gents"],
        "intro": "Series tied 1–1. This one decides it…",
        "rules": {**rules, "lines": ["One Lady vs one Gent", "A famous Bible quote, four names", "Pick who said it", "Right answer = 1 point"]},
        "matchups": matchups, "video": f"footage/{NAME}.mp4", "durationInSeconds": end,
        "boardTop": 440, "boardScale": 0.84, "captionY": 1560, "captions": caps,
        "stamps": [{"at": 0.2, "text": "The Decider", "tone": "gold", "duration": round(starts[1] - 0.3, 2)}] + stamps,
    }
    json.dump(props, open(os.path.join(HERE, "who-said-it.json"), "w"), indent=2, ensure_ascii=False)
    print(f"{len(segs)} segments, {end}s, {len(caps)} caption words, result {total}")


if __name__ == "__main__":
    main()
