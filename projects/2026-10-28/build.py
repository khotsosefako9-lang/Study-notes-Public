#!/usr/bin/env python3
"""Build the Church Feud rematch cut list and props from feud-plan.json.

  python3 projects/2026-10-28/build.py <transcripts dir>

The transcripts dir holds Whisper JSON for each clip (IMG_3379.json, ...), or
one-minute chunks named <clip>_<nn>.json. Times in the plan are source seconds;
everything is mapped onto the edited timeline here.
"""
import glob
import json
import math
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FPS = 30

QUESTIONS = [
    ("Name one of Jesus' twelve disciples.", ["Hlayi", "Yakha"],
     [("Peter", 32), ("John", 18), ("Judas", 14), ("Thomas", 10), ("Matthew", 9), ("James", 7), ("Andrew", 6), ("Philip", 4)]),
    ("Name an animal mentioned in the Bible.", ["Dibuseng", "Pastor Kyle"],
     [("Snake", 26), ("Lion", 20), ("Sheep", 18), ("Donkey", 12), ("Fish", 9), ("Dove", 8), ("Camel", 5), ("Pig", 2)]),
    ("Name one of the Ten Commandments.", ["Tanatswa", "Cwenga"],
     [("Do not murder", 28), ("Do not steal", 22), ("Honour your father and mother", 16), ("Do not commit adultery", 12),
      ("Keep the Sabbath holy", 8), ("No other gods", 7), ("Do not lie", 5), ("Do not covet", 2)]),
    ("Name a miracle Jesus performed.", ["Yinhla", "Lehlohonolo"],
     [("Water into wine", 26), ("Feeding the 5,000", 22), ("Walking on water", 18), ("Raising Lazarus", 14),
      ("Healing the blind", 10), ("Calming the storm", 6), ("Healing a leper", 4)]),
]
BANNED = re.compile(r"fuck|shit|damn|black man", re.I)


def load_words(tdir, clip):
    words = []
    full = os.path.join(tdir, f"IMG_{clip}.json")
    files = [(full, 0.0)] if os.path.exists(full) else [
        (f, 60.0 * int(re.search(r"_(\d+)\.json$", f).group(1))) for f in sorted(glob.glob(os.path.join(tdir, f"{clip}_*.json")))]
    for f, off in files:
        for s in json.load(open(f))["segments"]:
            for w in s.get("words", []):
                words.append({"text": w["word"].strip(), "start": w["start"] + off, "end": w["end"] + off})
    # Spelled-out letters come back as "C", "-O", "-V": glue them into one caption word.
    out = []
    for w in words:
        if out and w["text"].startswith("-"):
            out[-1]["text"] += w["text"]
            out[-1]["end"] = w["end"]
        else:
            out.append(w)
    return out


def main():
    tdir = sys.argv[1]
    plan = json.load(open(os.path.join(HERE, "feud-plan.json")))
    zoom = " ".join(str(z) for z in plan["zoom"])
    segs = plan["segments"]

    # Exact segment starts from roughcut.py when the cut has been built; an estimate otherwise.
    measured = os.path.join(HERE, "..", "..", "public", "footage", "feud-2026-10-28.segments.json")
    if os.path.exists(measured) and len(json.load(open(measured))["starts"]) == len(segs):
        m = json.load(open(measured))
        starts, end = m["starts"], round(sum(m["lengths"]), 2)
    else:
        starts, t = [], 0.0
        for s in segs:
            starts.append(t)
            t += math.ceil(round((s["b"] - s["a"]) * FPS, 3)) / FPS
        end = round(t, 2)
    out = lambda i, src: round(starts[i] + src - segs[i]["a"], 2)

    with open(os.path.join(HERE, "feud-cuts.txt"), "w") as f:
        f.write("# Church Feud rematch, Ladies vs Gents, 28 Oct 2026. Generated by build.py from feud-plan.json.\n")
        for s in segs:
            f.write(f"raw/2026-10-28/IMG_{s['clip']}.MOV {s['a']} {s['b']} {zoom}\n")

    rounds, stamps, rules = [], [], None
    for i, s in enumerate(segs):
        if "round" in s:
            q, players, answers = QUESTIONS[s["round"]]
            rounds.append({"at": out(i, s["roundAt"]), "round": f"Round {s['round'] + 1}", "players": players, "question": q,
                           "answers": [{"a": a, "pts": p} for a, p in answers], "strikes": [], "awards": []})
        r = rounds[-1] if rounds else None
        if "rules" in s:
            rules = {"at": out(i, s["rules"][0]) + 0.1, "until": out(i, s["rules"][1]) - 0.1}
        for name, at in s.get("flips", []):
            next(a for a in r["answers"] if a["a"] == name)["at"] = out(i, at)
        for at in s.get("strikes", []):
            r["strikes"].append(out(i, at))
        if "rest" in s:  # answers not shown being given: reveal dimmed, without points
            k = 0
            for a in r["answers"]:
                if "at" not in a:
                    a.update(at=round(out(i, s["rest"]) + 0.2 * k, 2), counts=False); k += 1
        if "award" in s:
            r["awards"].append({"at": out(i, s["award"][1]), "team": s["award"][0]})
        for text, tone, at, dur in ([s["stamp"]] if "stamp" in s else []) + s.get("stamps", []):
            stamps.append({"at": out(i, at), "text": text, "tone": tone, "duration": dur})
    if segs[0].get("hook"):
        stamps.insert(0, {"at": 0.25, "text": "The Rematch", "tone": "gold", "duration": round(starts[1] - 0.35, 2)})

    words = {c: load_words(tdir, c) for c in {s["clip"] for s in segs}}
    caps = []
    for i, s in enumerate(segs):
        fixes = plan["fixes"].get(s["clip"], {})
        drops = plan["dropWords"].get(s["clip"], [])
        for w in words[s["clip"]]:
            if w["start"] < s["a"] or w["start"] >= s["b"] - 0.05:
                continue
            # A drop is a time, or [word, time] when several words share a timestamp.
            if any(abs(w["start"] - d) < 0.05 if not isinstance(d, list) else (w["text"] == d[0] and abs(w["start"] - d[1]) < 0.15) for d in drops):
                continue
            text = fixes.get(w["text"], w["text"])
            caps.append({"text": text, "start": out(i, w["start"]), "end": out(i, min(w["end"], s["b"]))})
    bad = [c["text"] for c in caps if BANNED.search(c["text"])]
    if bad:
        sys.exit(f"Caption words need fixing before publishing: {bad}")

    props = {
        "title": "Church Feud: The Rematch", "question": "", "answers": [], "teams": ["Ladies", "Gents"],
        "intro": "The Gents lost 38–0 last week…", "rules": {**rules, "lines": [
            "One Lady vs one Gent per round",
            "Name the most popular answers",
            "Not on the board = strike ✕",
            "Win the round, win a point"]},
        "scoreBy": "rounds", "rounds": rounds,
        "video": "footage/feud-2026-10-28.mp4", "durationInSeconds": end,
        "layout": "split", "boardTop": 450, "boardScale": 0.82, "captionY": 1520,
        "captions": caps, "stamps": stamps,
    }
    json.dump(props, open(os.path.join(HERE, "feud.json"), "w"), indent=2, ensure_ascii=False)
    print(f"{len(segs)} segments, {end}s, {len(caps)} caption words")
    print("round starts:", [r["at"] for r in rounds])


if __name__ == "__main__":
    main()
